export function customerLanguageTools(language:CustomerLanguage){
 const locale=language==='en'?'en-GB':'th-TH';
 function t(value:string|number|null|undefined):string{
  const text=String(value??'');
  if(language==='th'||!text)return text;
  if(english[text])return english[text];
  const trimmed=text.trim();
  if(english[trimmed])return text.replace(trimmed,english[trimmed]);
  const numericMoney=trimmed.match(/^([-\d,.]+) บาท$/);
  if(numericMoney)return numericMoney[1]+' THB';
  const available=trimmed.match(/^พร้อมแลก ([\d,]+) ชิ้น$/);
  if(available)return 'Available: '+available[1]+' items';
  for(const prefix of ['กรอกข้อมูลสมัครสมาชิก รหัสลูกค้า','แลกได้ถึง','รูปสินค้า','ขนาด','เพิ่มลงตะกร้า','จำนวน','ลบ']){
   if(trimmed.startsWith(prefix+' '))return english[prefix]+' '+trimmed.slice(prefix.length+1);
  }
  if(text.includes(' · '))return text.split(' · ').map(part=>t(part)).join(' · ');
  return text;
 }
 return {language,locale,t,date:(value:Date)=>value.toLocaleDateString(locale,{timeZone:'Asia/Bangkok'}),money:(satang:number)=>(satang/100).toLocaleString(locale,{minimumFractionDigits:2,maximumFractionDigits:2})+' '+(language==='en'?'THB':'บาท')};
}
